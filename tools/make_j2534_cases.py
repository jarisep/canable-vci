"""Generate offline C++ RX expectations from the immutable stage 1 fixture.

The lifecycle case has no RX records; api_test.cpp tests its 124 channels.
No captured TX payload is replayed by this generator or the fixture test.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    source = ROOT / 'tests/fixtures/proace-reference.json'
    raw = source.read_bytes()
    fixture = json.loads(raw)
    assert fixture['auto_replay_to_vehicle'] is False
    lines = [
        '// SPDX-License-Identifier: Apache-2.0',
        '// Generated by tools/make_j2534_cases.py; offline use only.',
        '// Fixture SHA256: ' + hashlib.sha256(raw).hexdigest(),
        '#pragma once', '#include "j2534.hpp"', '#include <cstring>',
        '#include <vector>', '#include <string>',
        'struct CapturedCase {std::string name;std::vector<j::Msg> expected;};',
        'inline std::vector<CapturedCase> captured_cases(){std::vector<CapturedCase> all;',
    ]
    for case in fixture['cases']:
        records = [r for r in case['records']
                   if r.get('kind') == 'message' and r.get('direction') == 'RX']
        if not records:
            continue
        lines.append('{CapturedCase c;c.name=' + json.dumps(case['id']) + ';')
        for record in records:
            data = bytes.fromhex(record['data_hex'])
            assert len(data) == record['data_size']
            fields = {'ProtocolID': record['protocol'], 'RxStatus': record['rx_status'],
                      'TxFlags': record['tx_flags'], 'Timestamp': record['timestamp_us'],
                      'DataSize': len(data)}
            line = '{j::Msg m{};'
            line += ''.join(f'm.{name}={value}u;' for name, value in fields.items())
            line += 'm.ExtraDataIndex=m.DataSize;const uint8_t d[]={'
            line += ','.join(str(b) for b in data)
            line += '};std::memcpy(m.Data,d,sizeof(d));c.expected.push_back(m);}'
            lines.append(line)
        lines.append('all.push_back(c);}')
    lines.append('return all;}')
    return '\n'.join(lines) + '\n'


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    path = ROOT / 'windows/tests/captured_cases.hpp'
    expected = build()
    if args.check:
        if path.read_text() != expected:
            raise SystemExit('Generated J2534 cases differ; run this tool without --check.')
        print('Generated J2534 cases match the stage 1 fixture.')
    else:
        path.write_text(expected)


if __name__ == '__main__':
    main()
